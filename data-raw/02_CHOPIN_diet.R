# ---- 5. All dietary proportions ---------------------------------
# Counts and biomass are pooled across all retained G0 fish.
# Numerical denominator includes all retained taxa; biomass denominator
# includes only taxa with an estimated positive individual mass.

calc_diet_siphon <- function(factor_siphon) {

  # All three quantiles are corrected for the same BIVALVE siphon factor.
  # Earlier code applied the factor to all Mollusca quantiles; this is fixed.
  mass_test <- make_mass_chopin(factor_siphon) |>
    transmute(observed_species, Phylum, mass_median,
              mass_q25 = mass_minq25, mass_q75 = mass_maxq75)

  # Prey abundance and estimated biomass

  diet_sp <- stomach_contents_chopin |>
    group_by(observed_species) |>
    summarise(
      n_prey = sum(N_tract),
      n_fish = n_distinct(sample_TAG),
      .groups = "drop"
    ) |>
    left_join(
      mass_test,
      by = "observed_species",
      relationship = "many-to-one"
    ) |>
    mutate(
      mass_available = if_all(
        c(mass_median, mass_q25, mass_q75),
        ~ is.finite(.x) & .x > 0
      ),

      biomass_index = if_else(
        mass_available,
        n_prey * mass_median,
        NA_real_
      ),

      biomass_index_q25 = if_else(
        mass_available,
        n_prey * mass_q25,
        NA_real_
      ),

      biomass_index_q75 = if_else(
        mass_available,
        n_prey * mass_q75,
        NA_real_
      )
    )

  # Total prey abundance and biomass

  total_n <- sum(diet_sp$n_prey)
  total_b <- sum(diet_sp$biomass_index, na.rm = TRUE)
  total_b_q25 <- sum(diet_sp$biomass_index_q25, na.rm = TRUE)
  total_b_q75 <- sum(diet_sp$biomass_index_q75, na.rm = TRUE)
  if (
    !is.finite(total_b) || total_b <= 0 ||
    !is.finite(total_b_q25) || total_b_q25 <= 0 ||
    !is.finite(total_b_q75) || total_b_q75 <= 0
  ) {
    stop("No usable mass for at least one dietary scenario")
  }

  # Dietary proportions by prey taxon
  diet_sp <- diet_sp |>
    mutate(
      p_numeric = n_prey / total_n,
      p_biomass = if_else(
        mass_available,
        biomass_index / total_b,
        NA_real_
      ),
      p_biomass_q25 = if_else(
        mass_available,
        biomass_index_q25 / total_b_q25,
        NA_real_
      ),
      p_biomass_q75 = if_else(
        mass_available,
        biomass_index_q75 / total_b_q75,
        NA_real_
      ),
      factor_siphon = factor_siphon
    )

  # Aggregate proportions by phylum
  diet_phylum <- diet_sp |>
    group_by(Phylum) |>
    summarise(
      p_numeric = sum(p_numeric),
      p_biomass = sum(p_biomass, na.rm = TRUE),
      p_biomass_q25 = sum(p_biomass_q25, na.rm = TRUE),
      p_biomass_q75 = sum(p_biomass_q75, na.rm = TRUE),
      n_prey = sum(n_prey),
      n_prey_with_mass = sum(n_prey[mass_available], na.rm = TRUE),
      .groups = "drop"
    ) |>
    mutate(factor_siphon = factor_siphon)

  # Return both tables
  list(
    species = diet_sp,
    phylum = diet_phylum
  )
}

