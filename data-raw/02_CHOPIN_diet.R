make_mass_chopin <- function(factor_siphon) {
  stopifnot(length(factor_siphon) == 1, is.finite(factor_siphon),
            factor_siphon > 0)
  mass_chopin_base |>
    mutate(across(c(mass_median, mass_minq25, mass_maxq75),
                  ~ if_else(!is.na(Class) & Class == "Bivalvia", .x * factor_siphon, .x))) |>
    mutate(factor_siphon = factor_siphon) |>
    arrange(desc(mass_median))
}

