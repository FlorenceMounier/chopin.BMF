# Chemical references identified at genus level, e.g. Nephtys sp
chem_genus_refs <- tibble(chemical_taxon = chem_taxa) |>
  filter(str_detect(chemical_taxon, "^[A-Z][a-z]+ sp\\.?$")) |>
  mutate(genus = word(chemical_taxon, 1)) |>
  arrange(genus, chemical_taxon) |>
  distinct(genus, .keep_all = TRUE)

coverage_taxa <- tibble(observed_species = stomach_taxa) |>
  mutate(
    genus = word(observed_species, 1),
    exact_match = observed_species %in% chem_taxa
  ) |>
  left_join(
    chem_genus_refs,
    by = "genus",
    relationship = "many-to-many"
  ) |>
  mutate(
    match_class = case_when(
      exact_match ~ "Direct",
      !is.na(chemical_taxon) &
        str_detect(
          observed_species,
          "^[A-Z][a-z]+ [a-z]+$"
        ) ~ "Genus-level proxy",
      TRUE ~ "No specific match"
    ),
    chemical_reference = case_when(
      exact_match ~ observed_species,
      match_class == "Genus-level proxy" ~ chemical_taxon,
      TRUE ~ NA_character_
    )
  ) |>
  select(observed_species, match_class, chemical_reference)


