safe_median <- function(x) {
  x <- x[is.finite(x)]
  if (length(x) == 0) NA_real_ else median(x)
}
safe_quantile <- function(x, prob) {
  x <- x[is.finite(x)]
  if (length(x) == 0) NA_real_ else unname(quantile(x, prob))
}
safe_extreme <- function(x, fun = min) {
  x <- x[is.finite(x)]
  if (length(x) == 0) NA_real_ else fun(x)
}
safe_ratio <- function(a, b) {
  if_else(is.finite(a) & is.finite(b) & b > 0, a / b, NA_real_)
}
check_unique <- function(data, by) {
  d <- data |> count(across(all_of(by))) |> filter(n > 1)
  if (nrow(d)) stop("Duplicate keys: ", paste(by, collapse = ", "))
  invisible(TRUE)
}

